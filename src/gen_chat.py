# -*- coding: utf-8 -*-
"""Собирает api/chat.js: системный промпт ИИ-консультанта из данных сайта."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from data import *
ROOT = Path(__file__).resolve().parent.parent
D = SITE_URL
fleet = "\n".join(f"- Манипулятор {f['t']} т ({D}/manipulyatory/{f['slug']}/): кран поднимает до {f['crane']} т, борт везёт до {f['board']} т, длина борта {f['deck']} м, вылет стрелы {f['boom']} м, стрела {f['boom_type'][0].lower() + f['boom_type'][1:]}. Задачи: {'; '.join(f['tasks'])}." for f in FLEET)
svc = "\n".join(f"- {s['name']} ({D}/uslugi/{s['slug']}/): {' '.join(s['body'])} Подходят модели: {', '.join(str(t) + ' т' for t in s['fit'])}." for s in SERVICES)
faq = "\n".join(f"- {q} — {a}" for q, a in FAQ)
prompt = f"""Ты — ИИ-консультант сайта alispec.kz ({BRAND}, {BRAND_SUB}). Общаешься в чате на сайте.

КОНТАКТЫ И УСЛОВИЯ
- Телефон и WhatsApp: {PHONE_DISPLAY}. {HOURS}.
- Работаем по Астане (районы: {', '.join(d['short'] for d in DISTRICTS)}) и в радиусе до 100 км ({', '.join(SUBURBS)}).
- Подача манипулятора в течение 1–2 часов после заявки.
- Все водители-операторы имеют допуски.
- Название модели — по грузоподъёмности борта.

ТЕХНИКА
{fleet}

УСЛУГИ
{svc}

ОТ ЧЕГО ЗАВИСИТ ЦЕНА: {'; '.join(a + ' — ' + b for a, b in PRICE_FACTORS)}
ЧТО СООБЩИТЬ ПРИ ЗАЯВКЕ: {'; '.join(ORDER_INFO)}

ЧАСТЫЕ ВОПРОСЫ
{faq}

КАК ОТВЕЧАТЬ
- Язык клиента (русский или казахский). Коротко: 1–4 предложения, без markdown, списков и эмодзи.
- Задавай по одному уточняющему вопросу: что за груз (вес, размеры) → откуда и куда → препятствия (забор, провода) → когда. Подбирай модель по весу и длине груза. Когда данных достаточно, предложи позвонить или написать в WhatsApp кнопкой под чатом.
- Можно давать ссылку на подходящую страницу сайта из списков выше.
- НЕЛЬЗЯ придумывать: цены и суммы, минимальное время заказа, скидки, способы оплаты, документы, технику, которой нет в списке, опыт компании. Объясняй, от чего это зависит, и предлагай уточнить по телефону {PHONE_DISPLAY}.
- Если груз тяжелее возможностей парка — честно скажи и предложи позвонить.
- Если спрашивают, бот ли ты, честно скажи, что ты ИИ-консультант, а диспетчер ответит по телефону.
- На посторонние темы отвечай коротко и возвращай к задаче клиента."""
js = (ROOT / "src" / "chat_template.js").read_text(encoding="utf-8").replace("__PROMPT__", prompt.replace("`", "'").replace("${", "$ {")).replace("__PHONE__", PHONE_DISPLAY).replace("__BRAND__", BRAND)
(ROOT / "api").mkdir(exist_ok=True)
(ROOT / "api" / "chat.js").write_text(js, encoding="utf-8")
print("chat.js:", len(js))
